test('한글 조합 중에도 즉시 검색하고 조합 확정 Enter는 운동을 선택하지 않는다', async ({ page, db }) => {
  db.catalog.push(
    { id: 'dumbbell', name: '덤벨 벤치 프레스', category: '웨이트', target_parts: ['가슴', '팔'] },
    { id: 'squat', name: '스쿼트', category: '웨이트', target_parts: ['하체'] },
  )
  await page.goto('/')
  await page.getByRole('button', { name: /운동 기록하기/ }).first().click()
  const dialog = page.locator('dialog[open]')
  const name = dialog.getByLabel('운동 이름')
  await name.dispatchEvent('compositionstart')
  for (const value of ['ㄷ', '더', '덤']) {
    await name.evaluate((input, text) => {
      input.value = text
      input.dispatchEvent(new InputEvent('input', { bubbles: true, data: text, inputType: 'insertCompositionText', isComposing: true }))
    }, value)
  }
  await expect(dialog.getByRole('option')).toHaveCount(1)
  await expect(dialog.getByRole('option')).toContainText('덤벨 벤치 프레스')
  await expect(name).toBeFocused()
  await name.dispatchEvent('keydown', { key: 'Enter', keyCode: 229, isComposing: true })
  await expect(name).toHaveValue('덤')
  await expect(dialog.getByRole('listbox')).toBeVisible()
  await expect(dialog.getByRole('button', { name: /^가슴/ })).toHaveAttribute('aria-pressed', 'false')
  await name.dispatchEvent('compositionend', { data: '덤' })
  await dialog.getByRole('option').click()
  await expect(name).toHaveValue('덤벨 벤치 프레스')
  await expect(dialog.getByRole('listbox')).not.toBeVisible()
  await expect(dialog.getByRole('button', { name: /^가슴/ })).toHaveAttribute('aria-pressed', 'true')
})

test('추천 목록은 입력창 바로 아래 같은 너비로 연결되고 내부에서 스크롤된다', async ({ page, db }) => {
  for (let index = 0; index < 12; index++) {
    db.catalog.push({ id: `dumbbell-${index}`, name: `덤벨 운동 ${index}`, category: '웨이트', target_parts: ['팔'] })
  }
  await page.goto('/')
  await page.getByRole('button', { name: /운동 기록하기/ }).first().click()
  const dialog = page.locator('dialog[open]')
  const name = dialog.getByLabel('운동 이름')
  await name.fill('덤')
  const list = dialog.getByRole('listbox')
  await expect(list).toBeVisible()
  const inputBox = await name.boundingBox()
  const listBox = await list.boundingBox()
  expect(Math.abs(listBox.x - inputBox.x)).toBeLessThanOrEqual(1)
  expect(Math.abs(listBox.width - inputBox.width)).toBeLessThanOrEqual(1)
  expect(listBox.y - (inputBox.y + inputBox.height)).toBeGreaterThanOrEqual(0)
  expect(listBox.y - (inputBox.y + inputBox.height)).toBeLessThanOrEqual(6)
  expect(await list.evaluate((element) => element.scrollHeight > element.clientHeight)).toBe(true)
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await name.fill('')
  await expect(list).not.toBeVisible()
})

