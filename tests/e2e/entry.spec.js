test('10세트도 간결하게 배치하고 중량과 횟수를 나란히 입력한다', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /운동 기록하기/ }).first().click()
  const dialog = page.locator('dialog[open]')
  for (let index = 0; index < 10; index++) await dialog.getByRole('button', { name: '＋ 세트 추가' }).click()
  const rows = dialog.locator('.set-row')
  await expect(rows).toHaveCount(10)
  await expect(dialog.getByRole('checkbox')).toHaveCount(0)
  for (let index = 0; index < 10; index++) {
    const row = await rows.nth(index).boundingBox()
    expect(row.height).toBeLessThanOrEqual(110)
    const weight = await dialog.getByLabel(`${index + 1}세트 중량 (kg)`, { exact: true }).boundingBox()
    const reps = await dialog.getByLabel(`${index + 1}세트 횟수`, { exact: true }).boundingBox()
    expect(Math.abs(weight.y - reps.y)).toBeLessThanOrEqual(1)
    expect(reps.x).toBeGreaterThan(weight.x + weight.width)
  }
  await dialog.getByLabel('10세트 횟수', { exact: true }).fill('12')
  await dialog.getByRole('button', { name: '10세트 횟수 증가', exact: true }).click()
  await expect(dialog.getByLabel('10세트 횟수', { exact: true })).toHaveValue('13')
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await dialog.getByRole('button', { name: '5세트 삭제', exact: true }).click()
  await expect(rows).toHaveCount(9)
  await expect(dialog.getByLabel('9세트 횟수', { exact: true })).toHaveValue('13')
})

