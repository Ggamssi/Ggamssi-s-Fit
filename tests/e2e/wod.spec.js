import { test, expect } from '@playwright/test'

async function openWod(page, type = 'AMRAP', name = '') {
  await page.getByRole('button', { name: /운동 기록하기/ }).first().click()
  const dialog = page.locator('dialog[open]')
  await dialog.getByRole('button', { name: '크로스핏 와드', exact: true }).click()
  await dialog.getByLabel('와드 이름').fill(name)
  await dialog.getByRole('button', { name: type, exact: true }).click()
  await dialog.getByLabel('처방 구성').fill('10 thrusters 95lb\n10 pull-ups\n200m run')
  await dialog.getByRole('button', { name: '전신', exact: true }).click()
  return dialog
}

async function save(dialog) {
  await dialog.getByRole('button', { name: '기록 저장하기' }).click()
  await expect(dialog).not.toBeVisible()
}

test('AMRAP 구성과 Scaled 결과를 한 기록으로 저장·복원·필터·삭제한다', async ({ page }) => {
  const runtimeErrors = []
  page.on('pageerror', (error) => runtimeErrors.push(error.message))
  await page.goto('/')
  const dialog = await openWod(page)
  await expect(dialog.getByLabel('세트 수')).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Scaled', exact: true }).click()
  await dialog.getByLabel('실제 변경 내용').fill('95lb → 65lb, 풀업 → 링로우')
  await dialog.getByLabel('제한 시간').fill('12')
  await dialog.getByLabel('완료 라운드').fill('5')
  await dialog.getByLabel('추가 반복 수').fill('8')
  await dialog.getByLabel('마지막 진행량').fill('마지막 러닝 120m')
  await dialog.getByLabel('운동 시간 (분)', { exact: true }).fill('12')
  await save(dialog)
  const card = page.locator('.record-card')
  await expect(card).toHaveCount(1)
  await expect(card).toContainText('오늘의 와드')
  await expect(card).toContainText('5라운드 + 8회')
  await expect(card).toContainText('AMRAP · Scaled')
  await expect(card).toContainText('95lb → 65lb, 풀업 → 링로우')
  await expect(card).toContainText('마지막 러닝 120m')
  await expect(page.locator('.stat-card').nth(1).locator('strong')).toHaveText('1')
  await expect(page.locator('.stat-card').nth(2).locator('strong')).toHaveText('12')
  await page.reload()
  await expect(card).toContainText('5라운드 + 8회')
  await page.getByRole('button', { name: '웨이트', exact: true }).click()
  await expect(card).toHaveCount(0)
  await page.getByRole('button', { name: '크로스핏 와드', exact: true }).click()
  await expect(card).toHaveCount(1)
  page.once('dialog', (confirmation) => confirmation.accept())
  await page.getByRole('button', { name: '오늘의 와드 기록 삭제' }).click()
  await page.reload()
  await expect(card).toHaveCount(0)
  expect(runtimeErrors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('EMOM은 총 구간과 목표 달성 수·미달 상태를 검증한다', async ({ page }) => {
  await page.goto('/')
  const dialog = await openWod(page, 'EMOM', '15분 EMOM')
  await dialog.getByLabel('총 시간 / 구간 수').fill('15')
  await dialog.getByLabel('목표를 달성한 구간 수').fill('16')
  await dialog.getByRole('button', { name: '기록 저장하기' }).click()
  await expect(dialog.getByRole('alert')).toContainText('총 구간 수 이하')
  await dialog.getByLabel('목표를 달성한 구간 수').fill('13')
  await dialog.getByRole('button', { name: '기록 저장하기' }).click()
  await expect(dialog.getByRole('alert')).toContainText('수행 상태')
  await dialog.getByRole('button', { name: '일부 미달', exact: true }).click()
  await dialog.getByLabel('미달 / 중도 종료 내용').fill('14, 15분 버피 각 2회 부족')
  await save(dialog)
  await page.reload()
  await expect(page.locator('.record-card')).toContainText('15개 구간 중 13개 목표 달성')
  await expect(page.locator('.record-card')).toContainText('일부 미달')
  await expect(page.locator('.record-card')).toContainText('14, 15분 버피 각 2회 부족')
  await expect(page.locator('.stat-card').nth(2).locator('strong')).toHaveText('0')
})

test('FOR TIME 완주·타임캡 도달·중도 종료를 다른 결과로 보존한다', async ({ page }) => {
  await page.goto('/')
  let dialog = await openWod(page, 'FOR TIME', '완주 와드')
  await dialog.getByLabel('목표 라운드').fill('5')
  await dialog.getByLabel('타임캡').fill('15')
  await dialog.getByLabel('완주 시간 (분, 필수)', { exact: true }).fill('15')
  await dialog.getByLabel('완주 시간 (초, 필수)', { exact: true }).fill('1')
  await dialog.getByRole('button', { name: '기록 저장하기' }).click()
  await expect(dialog.getByRole('alert')).toContainText('타임캡을 초과')
  await dialog.getByLabel('완주 시간 (분, 필수)', { exact: true }).fill('9')
  await dialog.getByLabel('완주 시간 (초, 필수)', { exact: true }).fill('42')
  await save(dialog)
  for (const status of ['타임캡 도달', '중도 종료']) {
    dialog = await openWod(page, 'FOR TIME', status)
    await dialog.getByLabel('목표 라운드').fill('5')
    await dialog.getByLabel('타임캡').fill('15')
    await dialog.getByLabel('완주 시간 (분, 필수)', { exact: true }).fill('9')
    await dialog.getByLabel('완주 시간 (초, 필수)', { exact: true }).fill('42')
    await dialog.getByRole('button', { name: status, exact: true }).click()
    await expect(dialog.getByLabel('완주 시간 (분, 필수)', { exact: true })).toHaveCount(0)
    await dialog.getByLabel('완료 라운드').fill('4')
    await dialog.getByLabel('추가 반복 수').fill('6')
    await dialog.getByLabel('마지막 진행량').fill('러닝 200m')
    await save(dialog)
  }
  await page.reload()
  await expect(page.locator('.record-card').filter({ hasText: '완주 와드' })).toContainText('9분 42초 완주')
  for (const status of ['타임캡 도달', '중도 종료']) {
    const card = page.locator('.record-card').filter({ has: page.getByRole('heading', { name: status, exact: true }) })
    await expect(card).toContainText(`${status} · 4라운드 + 6회`)
    await expect(card).not.toContainText('9분 42초 완주')
  }
  const records = await page.evaluate(() => JSON.parse(localStorage.getItem('teamk.exercise.records.v1')))
  for (const record of records.filter((item) => item.wod.status !== 'completed')) expect(record.wod.finish_minutes).toBeUndefined()
})

test('방식 전환·기타 결과·다음 기록 초기화와 기존 일반 기록을 확인한다', async ({ page }) => {
  await page.addInitScript(() => {
    if (!localStorage.getItem('teamk.exercise.records.v1')) localStorage.setItem('teamk.exercise.records.v1', JSON.stringify([{ id: 'legacy', workout_date: new Date().toLocaleDateString('sv-SE'), name: '기존 스쿼트', category: '웨이트', body_parts: ['하체'], duration: 30, notes: '' }]))
  })
  await page.goto('/')
  await expect(page.locator('.record-card')).toContainText('기존 스쿼트')
  const dialog = await openWod(page)
  await dialog.getByLabel('제한 시간').fill('12')
  await dialog.getByLabel('완료 라운드').fill('5')
  await dialog.getByLabel('추가 반복 수').fill('8')
  await dialog.getByRole('button', { name: 'EMOM', exact: true }).click()
  await expect(dialog.getByLabel('제한 시간')).toHaveCount(0)
  await dialog.getByRole('button', { name: 'AMRAP', exact: true }).click()
  await expect(dialog.getByLabel('제한 시간')).toHaveValue('')
  await expect(dialog.getByLabel('완료 라운드')).toHaveValue('')
  await dialog.getByRole('button', { name: '기타', exact: true }).click()
  await dialog.getByLabel('결과 (필수)', { exact: true }).fill('팀 합계 150회')
  await save(dialog)
  await page.reload()
  await expect(page.locator('.record-card')).toHaveCount(2)
  await expect(page.locator('.record-card').filter({ hasText: '오늘의 와드' })).toContainText('팀 합계 150회')
  await page.getByRole('button', { name: /운동 기록하기/ }).first().click()
  await expect(dialog.getByRole('button', { name: '일반 운동', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await dialog.getByRole('button', { name: '크로스핏 와드', exact: true }).click()
  await expect(dialog.getByLabel('처방 구성')).toHaveValue('')
  await expect(dialog.getByRole('button', { name: 'AMRAP', exact: true })).toHaveAttribute('aria-pressed', 'true')
})