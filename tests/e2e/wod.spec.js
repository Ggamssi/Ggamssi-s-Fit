test('FOR TIME 완주·타임캡 도달·중도 종료를 다른 결과로 보존한다', async ({ page, db }) => {
  await page.goto('/')
  let dialog = await openWod(page, 'FOR TIME', '완주 와드')
  await dialog.getByRole('spinbutton', { name: /목표 라운드/ }).fill('5')
  await dialog.getByRole('spinbutton', { name: /타임캡/ }).fill('15')
  await dialog.getByLabel('완주 시간 (분, 필수)', { exact: true }).fill('15')
  await dialog.getByLabel('완주 시간 (초, 필수)', { exact: true }).fill('1')
  await dialog.getByRole('button', { name: '기록 저장하기' }).click()
  await expect(dialog.getByRole('alert')).toContainText('타임캡을 초과')
  await dialog.getByLabel('완주 시간 (분, 필수)', { exact: true }).fill('9')
  await dialog.getByLabel('완주 시간 (초, 필수)', { exact: true }).fill('42')
  await save(dialog)
  for (const status of ['타임캡 도달', '중도 종료']) {
    dialog = await openWod(page, 'FOR TIME', status)
    await dialog.getByRole('spinbutton', { name: /목표 라운드/ }).fill('5')
    await dialog.getByRole('spinbutton', { name: /타임캡/ }).fill('15')
    await dialog.getByLabel('완주 시간 (분, 필수)', { exact: true }).fill('9')
    await dialog.getByLabel('완주 시간 (초, 필수)', { exact: true }).fill('42')
    await dialog.getByRole('button', { name: status, exact: true }).click()
    await expect(dialog.getByLabel('완주 시간 (분, 필수)', { exact: true })).toHaveCount(0)
    await dialog.getByRole('spinbutton', { name: /완료 라운드/ }).fill('4')
    await dialog.getByRole('spinbutton', { name: /추가 반복 수/ }).fill('6')
    await dialog.getByLabel('마지막 진행량').fill('러닝 200m')
    await save(dialog)
  }
  await page.reload()
  await expect(page.locator('.record-card').filter({ hasText: '완주 와드' })).toContainText('9분 42초 완주')
  for (const status of ['타임캡 도달', '중도 종료']) {
    const card = page.locator('.record-card').filter({ has: page.getByRole('heading', { name: status, exact: true }) })
    await expect(card).toContainText(`${status} · 4라운드 + 6회`)
    await expect(card).not.toContainText('9분 42초 완주')
  }
  const records = db.records
  for (const record of records.filter((item) => item.wod.status !== 'completed')) expect(record.wod.finish_minutes).toBeUndefined()
})

